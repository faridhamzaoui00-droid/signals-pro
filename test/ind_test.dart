const _idx = [40, 50, 59];

void near(List<double> a, List<double> expected, String name) {
  for (var j = 0; j < _idx.length; j++) {
    expect(a[_idx[j]], closeTo(expected[j], 1e-8), reason: '$name @${_idx[j]}');
  }
}

void main() {
  final b = _bars();
  final byId = {for (final d in kIndicatorLib) d.id: d};

  test('SMA / EMA / WMA / RSI / ATR مطابقة للمرجع', () {
    near(byId['sma']!.calc(b, {'period': 20})['value']!, [1.0928745000000002, 1.092315, 1.0931275], 'sma20');
    near(byId['ema']!.calc(b, {'period': 20})['value']!, [1.0929647446790938, 1.0929474340668757, 1.0935964659027924], 'ema20');
    near(byId['wma']!.calc(b, {'period': 10})['value']!, [1.091652, 1.0931152727272728, 1.094149090909091], 'wma10');
    near(byId['rsi']!.calc(b, {'period': 14})['value']!, [26.934026735207937, 49.374096200181945, 54.134586938415154], 'rsi14');
    near(byId['atr']!.calc(b, {'period': 14})['value']!, [0.0013481576819656812, 0.001241602041421064, 0.0011701462876318564], 'atr14');
  });

  test('MACD (12,26,9) مطابق للمرجع', () {
    final r = byId['macd']!.calc(b, {'fast': 12, 'slow': 26, 'signal': 9});
    near(r['macd']!, [-0.0014668692476547118, -0.0003381423623987079, 0.0002566924546085758], 'macd');
    near(r['signal']!, [-0.0014554096481107265, -0.0007475587239756878, -5.6428490696152144e-05], 'signal');
    near(r['hist']!, [-1.1459599543985326e-05, 0.00040941636157697996, 0.00031312094530472795], 'hist');
  });

  test('Bollinger (20, 2) مطابق للمرجع (انحراف معياري للمجتمع)', () {
    final r = byId['bollinger']!.calc(b, {'period': 20, 'dev': 2});
    near(r['mid']!, [1.0928745000000002, 1.092315, 1.0931275], 'mid');
    near(r['upper']!, [1.0955218494291463, 1.0942084888433787, 1.0955012301868579], 'upper');
    near(r['lower']!, [1.090227150570854, 1.0904215111566211, 1.0907537698131422], 'lower');
    near(r['pctb']!, [0.00620421104677097, 0.8974145412218308, 0.8228041688319578], 'pctb');
    near(r['bw']!, [0.004844745538753312, 0.0034669282091316336, 0.00434300699023275], 'bw');
  });

  test('Stochastic (14, 3) مطابق للمرجع', () {
    final r = byId['stochastic']!.calc(b, {'k': 14, 'd': 3});
    near(r['k']!, [1.44628099173585, 90.75000000000047, 79.43037974683453], 'k');
    near(r['d']!, [9.426752608572405, 76.49999999999964, 83.31575246132199], 'd');
  });

  test('فترة التهيئة: لا قيم قبل اكتمال البيانات', () {
    final s = byId['sma']!.calc(b, {'period': 20})['value']!;
    expect(s[18].isNaN, true);  expect(s[19].isNaN, false);
    final m = byId['macd']!.calc(b, {'fast': 12, 'slow': 26, 'signal': 9});
    expect(m['macd']![24].isNaN, true);  expect(m['macd']![25].isNaN, false);
    expect(m['signal']![32].isNaN, true);  expect(m['signal']![33].isNaN, false);
    final r = byId['rsi']!.calc(b, {'period': 14})['value']!;
    expect(r[13].isNaN, true);  expect(r[14].isNaN, false);
  });

  test('استقلال الإعدادات: RSI 14 و RSI 21 لا يتداخلان', () {
    final a = byId['rsi']!.calc(b, {'period': 14})['value']!;
    final c21 = byId['rsi']!.calc(b, {'period': 21})['value']!;
    final a2 = byId['rsi']!.calc(b, {'period': 14})['value']!;
    expect((a[59] - c21[59]).abs() > 1e-6, true);
    expect(a2[59], a[59]);
  });

  test('التقاطعات', () {
    final x = [1.0, 2.0, 3.0, 2.0, 1.0];
    final y = [2.0, 2.0, 2.0, 2.0, 2.0];
    expect(crossUp(x, y, 2), true);    // 2<=2 ثم 3>2
    expect(crossUp(x, y, 1), false);
    expect(crossDown(x, y, 4), true);  // 2>=2 ثم 1<2
    expect(crossDown(x, y, 3), false);
    expect(crossAboveLevel(x, 2.5, 2), true);
    expect(crossBelowLevel(x, 1.5, 4), true);
  });

  test('كل مؤشر في المكتبة بمعرف فريد وإعدادات افتراضية', () {
    final ids = kIndicatorLib.map((d) => d.id).toList();
